// fixtureRepo builds a minimal fake module tree exercising every structural
// and advisory rule, then scans and parses it for the rules under test.
func fixtureRepo(t *testing.T) []*parsedFile {
	t.Helper()

	files := map[string]string{
		"go.mod": "module smart-wardrobe-be\n\ngo 1.25\n",

		// H1 fail: 801 lines in a production file.
		"internal/modules/alpha/presentation/handler/huge.go": longCommentFile("handler", 801),

		// H1 warning: 601 lines in a production file.
		"internal/modules/alpha/presentation/handler/long.go": longCommentFile("handler", 601),

		// H1 warning: 801 lines in a test file (relaxed threshold: 1200 fail).
		"internal/modules/alpha/presentation/handler/long_test.go": longCommentFile("handler_test", 801),

		// H4 layer skip: presentation imports same-module infrastructure.
		"internal/modules/alpha/presentation/handler/skipper.go": `package handler

import "smart-wardrobe-be/internal/modules/alpha/infrastructure/persistence"

var _ = persistence.Repo{}
`,

		// H4 cross-module: alpha imports beta domain entities.
		"internal/modules/alpha/presentation/handler/cross.go": `package handler

import "smart-wardrobe-be/internal/modules/beta/domain/entities"

var _ = entities.Widget{}
`,

		// H4 exempt: module-root provider.go may touch infrastructure.
		"internal/modules/alpha/presentation/contract/wiring.go": `package contract

import "smart-wardrobe-be/internal/modules/alpha/infrastructure/persistence"

var _ = persistence.Repo{}
`,
		"internal/modules/alpha/provider.go": `package alpha

import "smart-wardrobe-be/internal/modules/alpha/infrastructure/persistence"

var _ = persistence.Repo{}
`,

		// H2 + H8: three behavior-carrying structs and a bare errors.New.
		"internal/modules/alpha/application/usecase/multi.go": `package usecase

import "errors"

type A struct{}

func (A) Do() {}

type B struct{}

func (B) Do() {}

type C struct{}

func (C) Do() {}

func Bad() error {
	return errors.New("raw error")
}
`,

		// H7: persistence method uses Find prefix.
		"internal/modules/alpha/infrastructure/persistence/repo.go": `package persistence

type Repo struct{}

func (Repo) FindAll() []int { return nil }
`,

		// beta entities referenced by the cross-module fixture.
		"internal/modules/beta/domain/entities/e.go": `package entities

type Widget struct{}
`,

		// Generated files must never be flagged, even when huge.
		"internal/modules/alpha/presentation/handler/gen.go": "// Code generated by tool. DO NOT EDIT.\n\npackage handler\n\n" + strings.Repeat("// filler line\n", 900),
	}

	return mustScan(t, files)
}

// writeFixture materializes one file inside the temp repo tree.
func writeFixture(t *testing.T, root, rel, content string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(rel))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatalf("mkdir for %s: %v", rel, err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatalf("write %s: %v", rel, err)
	}
}

func longCommentFile(pkg string, lines int) string {
	var b strings.Builder
	b.WriteString("package " + pkg + "\n\n")
	for i := 0; i < lines-2; i++ {
		b.WriteString("// filler line\n")
	}
	return b.String()
}

func mustScan(t *testing.T, files map[string]string) []*parsedFile {
	t.Helper()
	root := t.TempDir()
	for rel, content := range files {
		writeFixture(t, root, rel, content)
	}
	pfs, err := scanTree(root)
	if err != nil {
		t.Fatalf("scanTree: %v", err)
	}
	return pfs
}

func find(t *testing.T, files []*parsedFile, path string) *parsedFile {
	t.Helper()
	for _, pf := range files {
		if pf.Path == path {
			return pf
		}
	}
	t.Fatalf("fixture file not found: %s", path)
	return nil
}

func violationsFor(violations []Violation, rule string) []Violation {
	var out []Violation
	for _, v := range violations {
		if v.RuleID == rule {
			out = append(out, v)
		}
	}
	return out
}

func TestCheckFileLengthThresholds(t *testing.T) {
	cases := []struct {
		name     string
		lines    int
		isTest   bool
		severity Severity
		wantNone bool
	}{
		{"production under warn", 400, false, "", true},
		{"production warn", 601, false, SeverityWarning, false},
		{"production fail", 801, false, SeverityFail, false},
		{"test under relaxed warn", 700, true, "", true},
		{"test warn", 801, true, SeverityWarning, false},
		{"test fail", 1201, true, SeverityFail, false},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			kind := fileProduction
			if tc.isTest {
				kind = fileTest
			}
			pf := &parsedFile{scannedFile: scannedFile{Path: "x.go", Type: kind, Lines: tc.lines}}
			got := checkFileLength(pf)
			if tc.wantNone {
				if len(got) != 0 {
					t.Fatalf("expected no violation, got %d", len(got))
				}
				return
			}
			if len(got) != 1 || got[0].Severity != tc.severity {
				t.Fatalf("expected one %s violation, got %+v", tc.severity, got)
			}
		})
	}
}

func TestStructuralRules(t *testing.T) {
	files := fixtureRepo(t)

	h1 := violationsFor(runStructuralRules(files), RuleH1)

	var hugeFail, longWarn, testWarn bool
	for _, v := range h1 {
		switch {
		case v.Location.File == "internal/modules/alpha/presentation/handler/huge.go" && v.Severity == SeverityFail:
			hugeFail = true
		case v.Location.File == "internal/modules/alpha/presentation/handler/long.go" && v.Severity == SeverityWarning:
			longWarn = true
		case v.Location.File == "internal/modules/alpha/presentation/handler/long_test.go" && v.Severity == SeverityWarning:
			testWarn = true
		}
	}
	if !hugeFail || !longWarn || !testWarn {
		t.Fatalf("H1 coverage incomplete: hugeFail=%v longWarn=%v testWarn=%v", hugeFail, longWarn, testWarn)
	}

	// The generated file must not appear in any violation.
	for _, v := range runStructuralRules(files) {
		if strings.HasSuffix(v.Location.File, "gen.go") {
			t.Fatalf("generated file flagged: %+v", v)
		}
	}

	h2 := violationsFor(runStructuralRules(files), RuleH2)
	if len(h2) != 1 || !strings.Contains(h2[0].Detail, "3 types (A, B, C)") {
		t.Fatalf("expected one H2 warning for multi.go, got %+v", h2)
	}
}

func TestBoundaryRules(t *testing.T) {
	files := fixtureRepo(t)
	h4 := violationsFor(runBoundaryRules(files), RuleH4)

	var crossModule, layerSkip, providerExempt, contractFlagged bool
	for _, v := range h4 {
		switch {
		case strings.HasPrefix(v.Detail, detailCrossModule) &&
			strings.HasSuffix(v.Location.File, "cross.go"):
			crossModule = true
		case strings.HasPrefix(v.Detail, detailLayerSkip) &&
			strings.HasSuffix(v.Location.File, "skipper.go"):
			layerSkip = true
		case strings.HasSuffix(v.Location.File, "provider.go"):
			providerExempt = true
		case strings.HasSuffix(v.Location.File, "wiring.go"):
			contractFlagged = true
		}
	}
	if !crossModule {
		t.Fatalf("expected cross-module violation for cross.go, got %+v", h4)
	}
	if !layerSkip {
		t.Fatalf("expected layer skip for skipper.go, got %+v", h4)
	}
	if providerExempt {
		t.Fatalf("module-root provider.go must be exempt from layer-skip rule")
	}
	if !contractFlagged {
		t.Fatalf("non-provider presentation file must not be exempt: wiring.go was not flagged")
	}
}

func TestConstantsImportExemptFromLayerSkip(t *testing.T) {
	files := mustScan(t, map[string]string{
		"go.mod": "module smart-wardrobe-be\n\ngo 1.25\n",
		// domain importing apperror constants is sanctioned by §V.
		"internal/modules/alpha/domain/money/money.go": `package money

import "smart-wardrobe-be/internal/shared/application/constants/apperror"

func Bad() error { return apperror.NewBadRequest("x") }
`,
	})

	if got := violationsFor(runBoundaryRules(files), RuleH4); len(got) != 0 {
		t.Fatalf("constants import must be exempt, got %+v", got)
	}
}

func TestAdvisoryRules(t *testing.T) {
	files := fixtureRepo(t)

	if got := violationsFor(runAdvisoryRules(files), RuleH7); len(got) != 1 ||
		got[0].Location.Symbol != "FindAll" {
		t.Fatalf("expected H7 warning for FindAll, got %+v", got)
	}

	h8 := violationsFor(runAdvisoryRules(files), RuleH8)
	if len(h8) != 1 || !strings.Contains(h8[0].Detail, "bare errors.New") {
		t.Fatalf("expected one H8 warning for errors.New in usecase, got %+v", h8)
	}

	h6 := violationsFor(runAdvisoryRules(files), RuleH6)
	// multi.go / repo.go / skipper.go base names each exist in one module only.
	// long.go handler duplicates? Only files in >=2 distinct modules qualify;
	// this fixture has none, so H6 must stay silent.
	if len(h6) != 0 {
		t.Fatalf("expected no H6 suggestion in single-module fixture, got %+v", h6)
	}
}

func TestDuplicationClustersAcrossModules(t *testing.T) {
	files := mustScan(t, map[string]string{
		"go.mod": "module smart-wardrobe-be\n\ngo 1.25\n",
		"internal/modules/alpha/application/helper.go": "package helper\n\nfunc A() int { return 1 }\n",
		"internal/modules/beta/application/helper.go":  "package helper\n\nfunc B() int { return 2 }\n",
	})

	h6 := violationsFor(runAdvisoryRules(files), RuleH6)
	if len(h6) != 1 || !strings.Contains(h6[0].Detail, "2 modules (internal/modules/alpha, internal/modules/beta)") {
		t.Fatalf("expected one H6 cluster for helper.go, got %+v", h6)
	}
}

func TestClassifyFile(t *testing.T) {
	gen := []byte("// Code generated by x. DO NOT EDIT.\n\npackage p\n")
	if got := classifyFile("a/b.go", gen); got != fileGenerated {
		t.Fatalf("expected generated, got %s", got)
	}
	if got := classifyFile("a/b_test.go", []byte("package p\n")); got != fileTest {
		t.Fatalf("expected test, got %s", got)
	}
	if got := classifyFile("a/b.go", []byte("package p\n")); got != fileProduction {
		t.Fatalf("expected production, got %s", got)
	}
}
